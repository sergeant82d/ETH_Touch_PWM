# PlatformIO pre-build script (platformio.ini extra_scripts): writes src/build_info.cpp on
# every build with the build time and the git commit, "+ changes" when the code differs from
# that commit. __DATE__/__TIME__ only changed when web_server.cpp happened to be recompiled,
# so the System tab showed Oct 10 for days (user, 2026-10-14). The file is git-ignored; only
# it is recompiled when the time changes.
Import("env")
import datetime, os, subprocess

root = env["PROJECT_DIR"]

def git(*args):
    try:
        return subprocess.check_output(["git", *args], cwd=root, stderr=subprocess.DEVNULL, text=True).strip()
    except Exception:
        return ""

commit = git("rev-parse", "--short", "HEAD") or "no git"
changed = bool(git("status", "--porcelain", "--untracked-files=no"))
when = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
info = "%s, commit %s%s" % (when, commit, " + changes" if changed else "")

path = os.path.join(root, "src", "build_info.cpp")
text = ("// Generated by tools/build_info.py on every build (git-ignored). Do not edit.\n"
        "#include \"build_info.h\"\n"
        "const char BUILD_INFO[] = \"%s\";\n" % info)
old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
if text != old:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print("Build info: " + info)
